"""Generates the app's launcher icons in the colours of the connected controllers.

The app can only switch between icons that ship with it (Android has no API for drawing a new
launcher icon), so there is one icon per set of 1 to 4 preset light colours: 255 icons. Each is
an activity-alias in the manifest; core/AppIconChoice picks one and device/AppIcon switches.

Usage, from the repository root: python3 tools/app_icons.py

Writes:
  app/src/main/res/drawable/ic_launcher_background.xml    the default: the PS players' colours
  app/src/main/res/drawable/ic_launcher_bg_<key>.xml      the other sets of colours
  app/src/main/res/mipmap-anydpi-v26/ic_launcher_<key>.xml
  the aliases between the markers in app/src/main/AndroidManifest.xml

A key lists the colours' indices in core/LedPalette, ascending: "0" is blue alone, "13" red and
pink, "0123" blue, red, green and pink (the default icon).
"""
import itertools
import math
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RES = os.path.join(ROOT, "app", "src", "main", "res")
MANIFEST = os.path.join(ROOT, "app", "src", "main", "AndroidManifest.xml")

# core/LedPalette.colors, in order.
PRESETS = ["0030FF", "FF0A14", "00FF2A", "FF1E8C", "FF5200", "00E5FF", "9A00FF", "FFB000", "FFFFFF"]
DEFAULT_KEY = "0123"
MAX_COLOURS = 4


def lights(n):
    """core/IconLights.layout: (x, y, radius) in the icon's 108 x 108 square."""
    if n == 1:
        return [(54, 54, 70)]
    if n == 2:
        return [(34, 54, 56), (74, 54, 56)]
    if n == 3:
        return [(54, 32, 50), (33, 72, 50), (75, 72, 50)]
    if n == 4:
        return [(30, 30, 50), (78, 30, 50), (30, 78, 50), (78, 78, 50)]
    return [(54 + 28 * math.cos(2 * math.pi * k / n - math.pi / 2), 54 + 28 * math.sin(2 * math.pi * k / n - math.pi / 2), 42)
            for k in range(n)]


def circle(cx, cy, r):
    return f"M{cx - r:g},{cy:g}a{r:g},{r:g} 0 1,0 {2 * r:g},0a{r:g},{r:g} 0 1,0 {-2 * r:g},0Z"


def gradient(kind, attrs, stops):
    items = "".join(f'<item android:offset="{o}" android:color="{c}" />' for o, c in stops)
    return f'<aapt:attr name="android:fillColor"><gradient android:type="{kind}" {attrs}>{items}</gradient></aapt:attr>'


def background(key):
    """Coloured lights blurred behind dark glass; the same layers as ControllersIcon.render."""
    square = "M0,0h108v108h-108Z"
    paths = [f'    <path android:fillColor="#FF0B0E1A" android:pathData="{square}" />']
    for (x, y, r), index in zip(lights(len(key)), key):
        rgb = PRESETS[int(index)]
        stops = [(0, f"#C7{rgb}"), (0.5, f"#5C{rgb}"), (1, f"#00{rgb}")]
        attrs = f'android:centerX="{x:g}" android:centerY="{y:g}" android:gradientRadius="{r:g}"'
        paths.append(f'    <path android:pathData="{circle(x, y, r)}">{gradient("radial", attrs, stops)}</path>')
    paths.append(f'    <path android:fillColor="#0DFFFFFF" android:pathData="{square}" />')
    sheen = gradient("linear", 'android:startX="0" android:startY="0" android:endX="0" android:endY="60"', [(0, "#2EFFFFFF"), (1, "#00FFFFFF")])
    paths.append(f'    <path android:pathData="{square}">{sheen}</path>')
    return ('<?xml version="1.0" encoding="utf-8"?>\n'
            '<!-- Generated by tools/app_icons.py. -->\n'
            '<vector xmlns:android="http://schemas.android.com/apk/res/android" xmlns:aapt="http://schemas.android.com/aapt"\n'
            '    android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">\n'
            + "\n".join(paths) + "\n</vector>\n")


def adaptive(key):
    return ('<?xml version="1.0" encoding="utf-8"?>\n'
            '<!-- Generated by tools/app_icons.py. -->\n'
            '<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n'
            f'    <background android:drawable="@drawable/ic_launcher_bg_{key}" />\n'
            '    <foreground android:drawable="@drawable/ic_launcher_foreground" />\n'
            '    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />\n'
            '</adaptive-icon>\n')


def alias(key):
    default = key == DEFAULT_KEY
    icon = "@mipmap/ic_launcher" if default else f"@mipmap/ic_launcher_{key}"
    round_icon = "@mipmap/ic_launcher_round" if default else icon
    return (f'        <activity-alias android:name=".icon.Lights{key}" android:enabled="{str(default).lower()}" android:exported="true" '
            f'android:icon="{icon}" android:roundIcon="{round_icon}" android:targetActivity=".MainActivity">'
            '<intent-filter><action android:name="android.intent.action.MAIN" />'
            '<category android:name="android.intent.category.LAUNCHER" /></intent-filter></activity-alias>')


def main():
    keys = ["".join(str(i) for i in combo)
            for n in range(1, MAX_COLOURS + 1) for combo in itertools.combinations(range(len(PRESETS)), n)]
    drawable = os.path.join(RES, "drawable")
    mipmap = os.path.join(RES, "mipmap-anydpi-v26")
    # Remove icons of sets that are no longer generated.
    for folder, pattern in [(drawable, r"ic_launcher_bg_\d+\.xml"), (mipmap, r"ic_launcher_\d+\.xml")]:
        for name in os.listdir(folder):
            if re.fullmatch(pattern, name):
                os.remove(os.path.join(folder, name))
    for key in keys:
        if key == DEFAULT_KEY:
            with open(os.path.join(drawable, "ic_launcher_background.xml"), "w") as f:
                f.write(background(key))
            continue
        with open(os.path.join(drawable, f"ic_launcher_bg_{key}.xml"), "w") as f:
            f.write(background(key))
        with open(os.path.join(mipmap, f"ic_launcher_{key}.xml"), "w") as f:
            f.write(adaptive(key))

    start = "        <!-- App icons, one per set of light colours: generated by tools/app_icons.py. -->"
    end = "        <!-- End of the generated app icons. -->"
    text = open(MANIFEST).read()
    block = start + "\n" + "\n".join(alias(k) for k in keys) + "\n" + end
    if start in text:
        text = re.sub(re.escape(start) + r".*?" + re.escape(end), lambda _: block, text, flags=re.S)
    else:
        text = text.replace("    </application>", block + "\n\n    </application>")
    with open(MANIFEST, "w") as f:
        f.write(text)
    print(f"{len(keys)} icons")


if __name__ == "__main__":
    main()
